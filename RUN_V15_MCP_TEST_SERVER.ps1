param([string]$PythonPath = '')
$ErrorActionPreference='Stop'
$root=Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $PythonPath) { $PythonPath=Join-Path $root '.venv314\Scripts\python.exe' }
if (-not (Test-Path $PythonPath)) { throw 'Python 3.14.6 environment missing' }
if (-not $env:V15_MCP_HMAC_SECRET -or -not $env:V15_MCP_HOST_TOKEN) { throw 'Trusted host must supply V15_MCP_HMAC_SECRET and V15_MCP_HOST_TOKEN; no credentials generated by MCP client' }
if ($env:V15_TEST_MCP_ENABLE -ne 'I_ACKNOWLEDGE_TEST_ONLY') { throw 'Test-only MCP enable acknowledgement missing' }
$container='m2_pg16_gate-postgres-1'
$dbUser=(docker exec $container printenv POSTGRES_USER).Trim()
$dbPassword=(docker exec $container printenv POSTGRES_PASSWORD).Trim()
$portLine=docker port $container 5432/tcp | Select-Object -First 1
$port=[int](($portLine -split ':')[-1]); $u=[uri]::EscapeDataString($dbUser); $pw=[uri]::EscapeDataString($dbPassword)
$env:M1_TEST_DATABASE_URL="postgresql://${u}:${pw}@127.0.0.1:${port}/industrial_lab_v15_test"
$env:V15_BUSINESS_DATABASE_URL="postgresql://${u}:${pw}@127.0.0.1:${port}/industrial_lab_v14_test"
$env:PYTHONPATH=Join-Path $root 'backend'
# No Write-Host: stdout reserved for JSON-RPC.
& $PythonPath -m app.mcp_v15.stdio_server
if ($LASTEXITCODE -ne 0) { throw 'MCP stdio server exited with error' }
